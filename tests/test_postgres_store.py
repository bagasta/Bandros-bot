def test_sql_translation_keeps_literals_and_conflicts() -> None:
    assert translate_sql("BEGIN IMMEDIATE") == ""
    assert translate_sql("UPDATE runs SET prompt = ? WHERE id = ?") == "UPDATE runs SET prompt = %s WHERE id = %s"
    assert (
        translate_sql("INSERT OR IGNORE INTO group_members VALUES (?, ?)")
        == "INSERT INTO group_members VALUES (%s, %s) ON CONFLICT DO NOTHING"
    )
    assert translate_sql("DELETE FROM messages WHERE content LIKE '[Grup %'") == (
        "DELETE FROM messages WHERE content LIKE '[Grup %%'"
    )
    queued = translate_sql(
        "INSERT INTO group_queue (group_id, bot_id) VALUES (?, ?) ON CONFLICT (group_id, bot_id) DO NOTHING"
    )
    assert queued.count("ON CONFLICT") == 1
    assert "%s" in queued
    event = translate_sql("INSERT INTO run_events (run_id, type, payload, created_at) VALUES (?, ?, ?, ?)")
    assert event.endswith("RETURNING id")


